// Regenerates llms.txt (index) and llms-full.txt (documents concatenated) from the repository.
// Usage: node tools/llms.cjs
const fs = require('node:fs'), path = require('node:path');
const root = path.join(__dirname, '..');
const B = 'https://github.com/riponcm/CharAI/blob/main/';
const exists = p => fs.existsSync(path.join(root, p));
const read = p => fs.readFileSync(path.join(root, p), 'utf8').replace(/\r\n/g, '\n').trim();
const pkg = JSON.parse(read('package.json'));

const summary = 'CharAI is an open-source (Apache 2.0) 2D character animation engine and agent skill. An AI agent, or a person, draws any human as a small data file and directs it with a short `.char` script; the engine supplies skeleton, motion, physics, moods, lip sync and speech, two-character contact and props. Characters only (the host supplies scenery), side view only in this release, no runtime dependencies, one script file `dist/char.js`. Exports MP4, transparent WebM and ProRes, PNG sequence and animated SVG. Version ' + pkg.version + '.';

const sections = [
  ['The skill', [
    ['SKILL.md', 'Start here: which document to read for each of the three jobs (draw a character, write a film, add an action).'],
    ['README.md', 'What CharAI is, the .char script, install as an agent skill, FAQ.'],
    ['AGENTS.md', 'Rules and commands for coding agents working in this repository.'],
  ]],
  ['Documents', [
    ['docs/CHARACTER.md', 'Draw a character: one skin file of numbers plus a few SVG paths.'],
    ['docs/RIG.md', 'The skin contract: every field and default.'],
    ['docs/AUTHORING.md', 'Write a film as a .char script: actors, actions, camera, captions.'],
    ['docs/ACTIONS.md', 'Action catalogue, moods, and how to write a new action.'],
    ['docs/SPEECH.md', 'Faces, expressions, speech and lip sync.'],
    ['docs/PAIRS.md', 'Two-character actions: hug, handshake, shove, hand over.'],
    ['docs/PROPS.md', 'Props: pick up, carry, throw, sit on, lean on.'],
    ['docs/HOSTS.md', 'Use CharAI from a web page, <char-stage>, HyperFrames, Remotion, GSAP; video and SVG export.'],
    ['docs/VOICE-WINDOWS.md', 'Make a voice track with the built-in Windows voices.'],
  ]],
  ['Evidence and limits', [
    ['docs/EVIDENCE.md', 'Measured token and time costs, including a comparison CharAI lost.'],
    ['docs/KNOWN-ISSUES.md', 'What is missing, wrong or untested in this release.'],
  ]],
];
const ex = [];
if (exists('examples')) for (const f of fs.readdirSync(path.join(root, 'examples')).sort()) {
  const isChar = f.endsWith('.char'), isHost = ['host.html', 'page.html', 'timeline.html'].includes(f);
  if (!isChar && !isHost && f !== 'README.md') continue;      // generated <name>.html pages are not listed
  let d = f === 'README.md' ? 'Index of the examples and a one-page tour of the .char language.' : 'Host page example (plain HTML).';
  if (isChar) {
    const first = fs.readFileSync(path.join(root, 'examples', f), 'utf8').split('\n')[0].replace(/^#\s*/, '').replace(/^\S+\.char\s*-\s*/, '').trim();
    d = 'Single-file .char example: ' + (first || 'a short film') + (/[.!?]$/.test(first) ? '' : '.');
  }
  ex.push(['examples/' + f, d]);
}
if (ex.length) sections.push(['Examples', ex]);
sections.push(['Optional', [['gallery/index.html', 'All preview clips on one page.']]]);

let idx = '# CharAI\n\n> ' + summary + '\n\n';
const full = [];
for (const [title, items] of sections) {
  idx += '## ' + title + '\n\n';
  for (const [p, d] of items) if (exists(p)) idx += '- [' + p + '](' + B + p + '): ' + d + '\n';
  idx += '\n';
}
fs.writeFileSync(path.join(root, 'llms.txt'), idx.trim() + '\n');

const order = ['README.md', 'SKILL.md', 'AGENTS.md', 'docs/CHARACTER.md', 'docs/RIG.md', 'docs/AUTHORING.md', 'docs/ACTIONS.md',
  'docs/SPEECH.md', 'docs/PAIRS.md', 'docs/PROPS.md', 'docs/HOSTS.md', 'docs/VOICE-WINDOWS.md', 'docs/EVIDENCE.md', 'docs/KNOWN-ISSUES.md', 'examples/README.md', 'examples/hello.char']
  .filter(exists);
let out = '# CharAI: full documentation\n\n> ' + summary + '\n\nGenerated by `node tools/llms.cjs`. Files in reading order; each begins with a separator line.\n';
for (const p of order) out += '\n\n========================================\nFILE: ' + p + '\nURL: ' + B + p + '\n========================================\n\n' + read(p) + '\n';
fs.writeFileSync(path.join(root, 'llms-full.txt'), out);
console.log('wrote llms.txt and llms-full.txt (' + order.length + ' files)');
